#!/usr/bin/env python3
"""Emit patches/modmenu/src/modmenu/MwApi.java from scriptapi.csv.

The game's script editor API panel is backed by scriptapi.csv inside
script_res.pkg; this reads the base table (names/signatures, untranslatable)
plus the en and vie descriptions and bakes one static row array into the mod
so the autocomplete and the checker work offline.

Usage: python3 tools/gen_mwapi.py
"""
import csv
import io
import os
import sys
import zipfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from pkgread import from_file  # noqa: E402

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
PKG_PATH = os.path.join(os.environ.get("PREFIX", ""), "tmp", "script_res.pkg")
BASE = "../commonresource/script/csvdef/utf8/scriptapi.csv"
LANG = {
    "en": "../script/language/en/csvdef/utf8/scriptapi.csv",
    "vie": "../script/language/vie/csvdef/utf8/scriptapi.csv",
}
OUT = os.path.join(REPO, "patches/modmenu/src/modmenu/MwApi.java")

# column layouts: base ships an extra Type/TypeName/ns triple up front
POS_BASE = {"id": 0, "ns": 3, "name": 4, "sig": 5, "params": 6, "ret": 7,
            "desc": 8, "example": 9}
POS_LANG = {"id": 0, "ns": 1, "name": 2, "sig": 3, "params": 4, "ret": 5,
            "desc": 6, "example": 7}


def ensure_pkg():
    if os.path.exists(PKG_PATH):
        return
    apkm = os.path.join(REPO, "work/source.apkm")
    with zipfile.ZipFile(apkm) as z:
        split = [n for n in z.namelist() if "asset" in n.lower()
                 and n.endswith(".apk")][0]
        with zipfile.ZipFile(io.BytesIO(z.read(split))) as s:
            data = s.read("assets/script_res.pkg")
    with open(PKG_PATH, "wb") as f:
        f.write(data)


def table(pkg, path, pos):
    txt = pkg.read(path).decode("utf-8")
    rows = list(csv.reader(io.StringIO(txt)))
    out = {}
    for r in rows[2:]:
        if len(r) <= pos["id"]:
            continue
        rid = r[pos["id"]].strip()
        if rid.isdigit():
            out[rid] = r
    return out, pos


def cell(r, pos, key):
    i = pos[key]
    if i >= len(r):
        return ""
    return " ".join(r[i].split())


def java_str(s):
    # \x01 separates fields; emit it as a unicode escape so the .java file
    # stays plain printable ASCII
    return s.replace("\\", "\\\\").replace('"', '\\"').replace("\x01", "\\u0001")


def main():
    ensure_pkg()
    pkg = from_file(PKG_PATH)
    base, pb = table(pkg, BASE, POS_BASE)
    langs = {}
    for code, path in LANG.items():
        if path in pkg.names():
            langs[code] = table(pkg, path, POS_LANG)

    rows = []
    for rid, r in base.items():
        ns = cell(r, pb, "ns")
        name = cell(r, pb, "name")
        if not ns or not name:
            continue
        desc = {"en": "", "vie": ""}
        for code, (tbl, pos) in langs.items():
            if rid in tbl:
                desc[code] = cell(tbl[rid], pos, "desc")
        fields = [ns, name, cell(r, pb, "sig"), cell(r, pb, "params"),
                  cell(r, pb, "ret"), desc["en"], desc["vie"],
                  cell(r, pb, "example")]
        rows.append("\x01".join(fields))
    rows.sort()

    with open(OUT, "w", encoding="utf-8") as f:
        f.write("package modmenu;\n\n")
        f.write("/**\n")
        f.write(" * UGC script API catalog - generated by tools/gen_mwapi.py\n")
        f.write(" * from the game's scriptapi.csv (base + en + vie tables).\n")
        f.write(" * Rows are ns\\u0001name\\u0001sig\\u0001params\\u0001ret\\u0001\n")
        f.write(" * descEn\\u0001descVi\\u0001example, one entry per line.\n")
        f.write(" */\n")
        f.write("final class MwApi {\n")
        f.write("    static final String[] ROWS = {\n")
        for row in rows:
            f.write('            "' + java_str(row) + '",\n')
        f.write("    };\n\n")
        f.write("    private MwApi() {\n    }\n")
        f.write("}\n")
    print("MwApi.java:", len(rows), "entries")


if __name__ == "__main__":
    main()
